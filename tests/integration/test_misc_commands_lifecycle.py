from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

import pytest
import yaml

from agsekit_cli.agents_modules import SUPPORTED_AGENT_TYPES
from tests.integration.utils import (
    REPO_ROOT,
    clean_env,
    random_vm_name,
    require_host_tools,
    run_cli,
    run_process,
    write_config,
)


pytestmark = pytest.mark.host_integration
pexpect = pytest.importorskip("pexpect")


@pytest.mark.skipif(os.name == "nt", reason="pexpect-based config-gen smoke test requires a POSIX PTY")
def test_config_example_and_gen(tmp_path: Path) -> None:
    example_path = tmp_path / "config-example.yaml"
    run_cli(["config-example", str(example_path)], check=True, cwd=tmp_path)
    assert example_path.exists()

    generated_path = tmp_path / "config-gen.yaml"
    env = clean_env(
        {
            "AGSEKIT_LANG": "en",
            "TERM": "xterm-256color",
            "PYTHONUNBUFFERED": "1",
            "COLUMNS": "120",
            "LINES": "40",
        }
    )
    child = pexpect.spawn(
        sys.executable,
        [str(REPO_ROOT / "agsekit"), "config-gen", "--config", str(generated_path), "--overwrite"],
        cwd=str(tmp_path),
        env=env,
        encoding="utf-8",
        timeout=20,
    )

    child.expect_exact("VM name")
    child.sendline("")
    child.expect_exact("How many vCPUs to allocate")
    child.sendline("")
    child.expect_exact("RAM size")
    child.sendline("")
    child.expect_exact("Disk size")
    child.sendline("")
    child.expect_exact("Select install bundles for this VM")
    child.sendline("")
    child.expect_exact("Proxychains proxy URL")
    child.sendline("")
    child.expect_exact("VM HTTP proxy URL")
    child.sendline("")
    child.expect_exact("Configure port-forwarding for this VM?")
    child.send("n")
    child.expect_exact("Add another VM?")
    child.send("n")
    child.expect_exact("Agent type")
    child.expect_exact("Cancel")
    child.send("j" * len(SUPPORTED_AGENT_TYPES))
    child.send("\r")
    child.expect_exact("Do you want to configure mounts?")
    child.send("n")
    child.expect_exact("Customize global agsekit settings?")
    child.send("n")
    child.expect_exact("Where should the config be saved?")
    child.sendline("")
    child.expect(pexpect.EOF)
    child.close()

    assert child.exitstatus == 0, child.before
    assert generated_path.exists()

    config = yaml.safe_load(generated_path.read_text(encoding="utf-8"))
    assert config == {
        "vms": {
            "agent-ubuntu": {
                "cpu": 2,
                "ram": "4G",
                "disk": "20G",
            }
        }
    }


