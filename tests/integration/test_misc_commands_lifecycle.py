def test_check_new_version_updates_custom_state_file(tmp_path: Path) -> None:
    state_path = tmp_path / "state.yaml"
    config_path = tmp_path / "config.yaml"
    write_config(
        config_path,
        {
            "global": {
                "state_file": str(state_path),
                "check_new_version": False,
            }
        },
    )

    result = run_cli(["check-new-version", "--config", str(config_path)], check=True, cwd=tmp_path)
    assert result.returncode == 0
    assert state_path.exists()

    raw_state = state_path.read_text(encoding="utf-8")
    assert raw_state.startswith("# Do not edit this file manually; it is generated by agsekit.\n")

    payload = yaml.safe_load(raw_state)
    assert payload["current_version"]
    assert payload["last_Version"]
    assert "check-new-version" not in result.stderr


def test_shell_requires_vm_when_multiple(tmp_path: Path) -> None:
    vm_one = random_vm_name("it-shell")
    vm_two = random_vm_name("it-shell")
    config_path = tmp_path / "config.yaml"
    write_config(
        config_path,
        {
            "vms": {
                vm_one: {"cpu": 1, "ram": "1G", "disk": "5G"},
                vm_two: {"cpu": 1, "ram": "1G", "disk": "5G"},
            }
        },
    )
    result = run_cli(["shell", "--config", str(config_path), "--non-interactive"], check=False)
    assert result.returncode != 0


